def language_of(code: str) -> str:
    """BCP 47 tag to its primary subtag, e.g. zh-CN -> zh; empty means English."""
    return (code or "en").split("-")[0].strip().lower() or "en"


def _localized(table: dict[str, str], language: str) -> str:
    return table.get(language_of(language)) or table["en"]


def _emergency(profile: Profile, language: str) -> str:
    return _localized(profile.emergency, language)


def welcome(profile_key: str, language: str, ahead: int, reorders: bool) -> str:
    profile = PROFILES[profile_key]
    reorder = _localized(REORDER, language) if reorders else ""
    text = _localized(WELCOME, language).format(ahead=ahead, reorder=reorder, emergency=_emergency(profile, language))
    return f"{text} {profile.welcome_extra}".strip()


def line(profile_key: str, key: str, language: str) -> str:
    return _localized(LINES[key], language).format(emergency=_emergency(PROFILES[profile_key], language))


def fallback_question(topic: str, language: str) -> str:
    return "" if topic == "wait" else _localized(QUESTIONS, language)[topic]
